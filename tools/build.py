#!/usr/bin/env python3
"""Validate the bank, then emit app-data.js. Refuses to build on any failure.

    .venv/bin/python tools/build.py
"""

import json
import sys

import lib
from validate import validate


def main():
    failed, lessons = validate()
    if failed:
        print("build refused: fix the lessons above first", file=sys.stderr)
        return 1
    course = lib.load_course()
    payload = {
        "course": course,
        "lessons": lessons,
        "datasets": lib.load_datasets(),
        "runner": (lib.ROOT / "engine" / "runner.py").read_text(),
    }
    out = lib.ROOT / "app-data.js"
    out.write_text("// Generated by tools/build.py. Do not edit.\nwindow.LAB = " + json.dumps(payload) + ";\n")
    print(f"wrote {out.name}: {len(lessons)} lessons, {out.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
